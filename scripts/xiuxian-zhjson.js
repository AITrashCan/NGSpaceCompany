// 按长度排序 key，长的优先替换避免部分匹配
const sortedKeys = Object.keys(keyMap).sort((a, b) => b.length - a.length);

// ==================== 生成 zh.json ====================

const zhJson = {};
for (const [origKey, origValue] of Object.entries(enJson)) {
    let newKey = origKey;
    for (const orig of sortedKeys) {
        if (origKey === orig) {
            newKey = keyMap[orig];
            break;
        }
        // also try prefix match for keys like "techEnergyStorage5_desc"
        if (origKey.startsWith(orig + '_')) {
            const suffix = origKey.slice(orig.length);
            if (keyMap[orig]) {
                newKey = keyMap[orig] + suffix;
                break;
            }
        }
    }
    // Values stay as-is for now (will be manually translated later)
    zhJson[newKey] = origValue;
}

// Write zh.json
const zhPath = path.join(__dirname, '..', 'src', 'locales', 'zh.json');
fs.writeFileSync(zhPath, JSON.stringify(zhJson, null, 4) + '\n', 'utf8');
console.log(`Generated zh.json with ${Object.keys(zhJson).length} entries`);

// Count unmapped keys (keys that weren't changed)
let unmapped = 0;
for (const [origKey] of Object.entries(enJson)) {
    let found = false;
    for (const orig of sortedKeys) {
        if (origKey === orig || origKey.startsWith(orig + '_')) {
            found = true;
            break;
        }
    }
    if (!found) unmapped++;
}
console.log(`Keys not in mapping (kept original): ${unmapped}`);
